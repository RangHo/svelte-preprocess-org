import { a, list, quote, type Atom, type Value } from "./emacs";
import { toKebabCase } from "./utilities";

/**
 * Customization options for Org export engine.
 *
 * See the documentation for `ox` for more details.
 */
export type OrgExportCustomization = Partial<{
  /**
   * Whether to activate smart quotes during export.
   *
   * When enabled, straight quote characters (`"`/`'`) are turned into
   * "curly" typographic quotes appropriate for the document's language.
   *
   * Equivalent to the `#+OPTIONS: ':t` keyword. See `org-export-with-smart-quotes`.
   */
  withSmartQuotes: boolean;

  /**
   * Whether to interpret `*word*`, `/word/`, `_word_` and `+word+` as
   * emphasis markup.
   *
   * If the export target supports emphasizing text, the word is typeset
   * in bold, italic, with an underline, or with a strike-through,
   * respectively.
   *
   * Equivalent to the `#+OPTIONS: *:nil` keyword. See `org-export-with-emphasize`.
   */
  withEmphasize: boolean;

  /**
   * Whether to interpret `\-`, `--` and `---` as hyphenation hints, en
   * dashes and em dashes (and `...` as an ellipsis) during export.
   *
   * Equivalent to the `#+OPTIONS: -:nil` keyword. See `org-export-with-special-strings`.
   */
  withSpecialStrings: boolean;

  /**
   * Whether to export lines starting with `:` as fixed-width (verbatim)
   * text.
   *
   * Equivalent to the `#+OPTIONS: ::nil` keyword. See `org-export-with-fixed-width`.
   */
  withFixedWidth: boolean;

  /**
   * Whether to allow timestamps in the exported document.
   *
   * Only applies to timestamps isolated in a paragraph containing only
   * timestamps; other timestamps are always exported.
   *
   * Equivalent to the `#+OPTIONS: <:nil` keyword. See `org-export-with-timestamps`.
   */
  withTimestamps: boolean;

  /**
   * Whether to preserve all line breaks when exporting.
   *
   * Equivalent to the `#+OPTIONS: \n:t` keyword. See `org-export-preserve-breaks`.
   */
  preserveBreaks: boolean;

  /**
   * Whether to interpret `_` and `^` as sub/superscript markers.
   *
   * Besides `true`/`false`, this can be set to the atom `{}` to require
   * that subscripts/superscripts be wrapped in curly braces (e.g. `a_{10}`)
   * to be recognized.
   *
   * Equivalent to `#+OPTIONS: ^:t`. See `org-export-with-sub-superscripts`
   * and `org-use-sub-superscripts`.
   */
  withSubSuperscripts: boolean | Atom;

  /**
   * Whether sub-trees tagged `ARCHIVE` should be exported.
   *
   * - `false` — do not export, pretend the tree is not present.
   * - `true` — export the entire tree.
   * - the atom `headline` — only export the headline, skipping its contents.
   *
   * Equivalent to the `#+OPTIONS: arch:nil` keyword. See `org-export-with-archived-trees`.
   */
  withArchivedTrees: boolean | Atom;

  /**
   * Whether to expand environment variables in file paths during export.
   *
   * See `org-export-expand-links`.
   */
  expandLinks: boolean;

  /**
   * Whether to suppress errors on broken links.
   *
   * When non-nil, broken links no longer stop the export process. Set to
   * the atom `mark` to instead replace broken links with a placeholder
   * string like `[BROKEN LINK: path]` in the output.
   *
   * Equivalent to the `#+OPTIONS: broken-links:mark` keyword. See `org-export-with-broken-links`.
   */
  withBrokenLinks: boolean | Atom;

  /**
   * Whether to export `CLOCK` keywords.
   *
   * Equivalent to the `#+OPTIONS: c:t` keyword. See `org-export-with-clocks`.
   */
  withClocks: boolean;

  /**
   * Whether the postamble should contain a creator sentence (e.g.
   * "Generated by Org mode X.X in Emacs XX.X").
   *
   * Equivalent to the `#+OPTIONS: creator:t` keyword. See `org-export-with-creator`
   * and `org-export-creator-string`.
   */
  withCreator: boolean;

  /**
   * Whether to export the contents of standard drawers.
   *
   * Does not apply to property drawers; see {@link withProperties} instead.
   *
   * Equivalent to the `#+OPTIONS: d:nil` keyword. See `org-export-with-drawers`.
   */
  withDrawers: boolean;

  /**
   * Whether to insert the document date in the exported document.
   *
   * Equivalent to the `#+OPTIONS: date:nil` keyword. See `org-export-with-date`.
   */
  withDate: boolean;

  /**
   * Whether to interpret entities (e.g. `\alpha`, `\AA`) during export.
   *
   * See the `org-entities` constant and the `org-entities-user` option for
   * the list of supported names.
   *
   * Equivalent to the `#+OPTIONS: e:nil` keyword. See `org-export-with-entities`.
   */
  withEntities: boolean;

  /**
   * Whether to insert the author's email into the exported file.
   *
   * Equivalent to the `#+OPTIONS: email:t` keyword. See `org-export-with-email`.
   */
  withEmail: boolean;

  /**
   * Whether Org footnotes should be exported.
   *
   * Equivalent to the `#+OPTIONS: f:nil` keyword. See `org-export-with-footnotes`.
   */
  withFootnotes: boolean;

  /**
   * The deepest headline level that is still exported as a headline.
   *
   * Descendants beyond this level usually produce itemized or enumerated
   * lists instead, though this depends on the export backend.
   *
   * Equivalent to the `#+OPTIONS: H:2` keyword. See `org-export-headline-levels`.
   */
  headlineLevels: number;

  /**
   * Whether inline tasks should be exported.
   *
   * Equivalent to the `#+OPTIONS: inline:nil` keyword. See `org-export-with-inlinetasks`.
   */
  withInlinetasks: boolean;

  /**
   * Whether to add section numbers to headlines when exporting.
   *
   * When set to a number `n`, numbering only applies to headlines whose
   * relative level is greater than or equal to `n`.
   *
   * Equivalent to the `#+OPTIONS: num:t` keyword. See `org-export-with-section-numbers`.
   */
  withSectionNumbers: boolean | number;

  /**
   * Whether to include planning info (the line with `SCHEDULED:`,
   * `DEADLINE:` and/or `CLOSED:` timestamps) in the export.
   *
   * Equivalent to the `#+OPTIONS: p:t` keyword. See `org-export-with-planning`.
   */
  withPlanning: boolean;

  /**
   * Whether to include priority cookies (e.g. `[#A]`) in the export.
   *
   * Equivalent to the `#+OPTIONS: pri:t` keyword. See `org-export-with-priority`.
   */
  withPriority: boolean;

  /**
   * Whether to export the contents of property drawers.
   *
   * `true` exports all properties; an array of strings exports only the
   * named properties.
   *
   * Equivalent to the `#+OPTIONS: prop:t` keyword. See `org-export-with-properties`.
   */
  withProperties: boolean | Atom[];

  /**
   * Whether to include statistics cookies (e.g. `[2/5]`, `[40%]`) in the
   * export.
   *
   * Equivalent to the `#+OPTIONS: stat:nil` keyword. See `org-export-with-statistics-cookies`.
   */
  withStatisticsCookies: boolean;

  /**
   * Whether to export tags attached to headlines.
   *
   * `false` removes tags entirely. The atom `not-in-toc` keeps tags in
   * headlines but strips them from table-of-contents entries.
   *
   * Equivalent to the `#+OPTIONS: tags:nil` keyword. See `org-export-with-tags`.
   */
  withTags: boolean | Atom;

  /**
   * Whether to include TODO items in the export.
   *
   * - `true` — include tasks regardless of state.
   * - `false` — ignore all tasks.
   * - the atom `todo` — include only tasks that are not yet done.
   * - the atom `done` — include only tasks that are already done.
   *
   * Equivalent to the `#+OPTIONS: tasks:nil` keyword. See `org-export-with-tasks`.
   */
  withTasks: boolean | Atom;

  /**
   * Whether to process LaTeX environments and fragments.
   *
   * - `true` — allow export of math snippets.
   * - `false` — ignore math snippets.
   * - the atom `verbatim` — keep everything in verbatim.
   *
   * Equivalent to the `#+OPTIONS: tex:verbatim` keyword. See `org-export-with-latex`.
   */
  withLatex: boolean | Atom;

  /**
   * Whether to insert a timestamp into the exported file showing when it
   * was created.
   *
   * Equivalent to the `#+OPTIONS: timestamp:nil` keyword. See `org-export-timestamp-file`.
   */
  timestampFile: boolean;

  /**
   * Whether to print the document title in the exported file.
   *
   * Equivalent to the `#+OPTIONS: title:nil` keyword. See `org-export-with-title`.
   */
  withTitle: boolean;

  /**
   * Whether to create a table of contents in the exported file.
   *
   * The table of contents contains headlines up to {@link headlineLevels}.
   *
   * Equivalent to the `#+OPTIONS: toc:nil` keyword. See `org-export-with-toc`.
   */
  withToc: boolean;

  /**
   * Whether to include TODO keywords (e.g. `TODO`, `DONE`) in the export.
   *
   * When `false`, these keywords are stripped from the export.
   *
   * Equivalent to the `#+OPTIONS: todo:nil` keyword. See `org-export-with-todo-keywords`.
   */
  todoKeywords: boolean;

  /**
   * Whether to export tables.
   *
   * Equivalent to the `#+OPTIONS: |:nil` keyword. See `org-export-with-tables`.
   */
  withTables: boolean;
}>;

/**
 * Generate Emacs Lisp code to customize the Org export engine.
 */
export function customize(options: OrgExportCustomization = {}) {
  const transformed = Object.entries(options).flatMap(([key, val]) => {
    switch (key) {
      case "withProperties": {
        return [
          a`org-export-with-properties`,
          Array.isArray(val) ? quote(list(...val)) : val,
        ];
      }

      case "withSmartQuotes":
      case "withEmphasize":
      case "withSpecialStrings":
      case "withFixedWidth":
      case "withTimestamps":
      case "preserveBreaks":
      case "withSubSuperscripts":
      case "withArchivedTrees":
      case "expandLinks":
      case "withBrokenLinks":
      case "withClocks":
      case "withCreator":
      case "withDrawers":
      case "withDate":
      case "withEntities":
      case "withEmail":
      case "withFootnotes":
      case "headlineLevels":
      case "withInlinetasks":
      case "withSectionNumbers":
      case "withPlanning":
      case "withPriority":
      case "withStatisticsCookies":
      case "withTags":
      case "withTasks":
      case "withLatex":
      case "timestampFile":
      case "withTitle":
      case "withToc":
      case "todoKeywords":
      case "withTables":
        return [a`org-export-${toKebabCase(key)}`, val as Value];

      default:
        return [];
    }
  });

  return list(a`setq`, ...transformed);
}
